package it.ttsserverproxy;

import android.os.Bundle;
import android.speech.tts.TextToSpeech;
import android.speech.tts.Voice;
import android.view.Gravity;
import android.widget.ArrayAdapter;
import android.widget.LinearLayout;
import android.widget.ScrollView;
import android.widget.Spinner;
import android.widget.TextView;

import com.google.android.material.button.MaterialButton;
import com.google.android.material.card.MaterialCardView;
import com.google.android.material.textfield.TextInputEditText;
import com.google.android.material.textfield.TextInputLayout;

import java.util.ArrayList;
import java.util.Locale;
import java.util.Set;

public class TestActivity extends androidx.appcompat.app.AppCompatActivity {
    private TextView out;

    @Override public void onCreate(Bundle b) {
        super.onCreate(b);
        ScrollView scroll = new ScrollView(this);
        scroll.setFillViewport(true);
        scroll.setBackgroundColor(Ui.attr(this, com.google.android.material.R.attr.colorSurface));
        LinearLayout root = new LinearLayout(this);
        root.setOrientation(LinearLayout.VERTICAL);
        root.addView(Ui.header(this, "Synthesis test",
                "Testing the TTS engine through the public Android API"));

        MaterialCardView cardC = Ui.card(this);
        LinearLayout card = Ui.into(this, cardC);
        card.addView(Ui.sectionLabel(this, "Text and voice"));

        TextInputLayout textL = new TextInputLayout(this, null,
                com.google.android.material.R.style.Widget_Material3_TextInputLayout_OutlinedBox);
        textL.setHint("Text to speak");
        textL.setBoxBackgroundMode(TextInputLayout.BOX_BACKGROUND_OUTLINE);
        TextInputEditText t = new TextInputEditText(textL.getContext());
        t.setSingleLine(false);
        t.setMinLines(2);
        t.setText("Hello, this is a test of the voice generated by the server on the local network.");
        textL.addView(t);
        card.addView(textL, Ui.lp(LinearLayout.LayoutParams.MATCH_PARENT,
                LinearLayout.LayoutParams.WRAP_CONTENT, 0, 0, 0, Ui.dp(this, 14)));

        TextView vl = new TextView(this);
        vl.setText("Engine voice");
        vl.setTextSize(13);
        vl.setTextColor(Ui.attr(this, com.google.android.material.R.attr.colorOnSurfaceVariant));
        vl.setPadding(0, 0, 0, Ui.dp(this, 6));
        card.addView(vl);

        final Spinner voices = new Spinner(this);
        card.addView(voices, Ui.lp(LinearLayout.LayoutParams.MATCH_PARENT,
                LinearLayout.LayoutParams.WRAP_CONTENT, 0, 0, 0, Ui.dp(this, 16)));

        LinearLayout row = new LinearLayout(this);
        row.setOrientation(LinearLayout.HORIZONTAL);
        row.setGravity(Gravity.CENTER_VERTICAL);
        MaterialButton speak = new MaterialButton(this); // filled
        speak.setText("🔊 Speak");
        speak.setAllCaps(false);
        row.addView(speak, Ui.lp(LinearLayout.LayoutParams.WRAP_CONTENT,
                LinearLayout.LayoutParams.WRAP_CONTENT, 0, 0, Ui.dp(this, 10), 0));
        MaterialButton all = Ui.tonal(this, "Try all voices");
        row.addView(all, Ui.lp(LinearLayout.LayoutParams.WRAP_CONTENT,
                LinearLayout.LayoutParams.WRAP_CONTENT, 0, 0, 0, 0));
        card.addView(row);
        root.addView(cardC);

        MaterialCardView resCardC = Ui.card(this);
        LinearLayout resCard = Ui.into(this, resCardC);
        resCard.addView(Ui.sectionLabel(this, "Status"));
        out = new TextView(this);
        out.setTextSize(14);
        out.setTextColor(Ui.attr(this, com.google.android.material.R.attr.colorOnSurface));
        out.setText("Initializing…");
        resCard.addView(out);
        root.addView(resCardC);

        scroll.addView(root);
        setContentView(scroll);

        final TextToSpeech[] holder = new TextToSpeech[1];
        holder[0] = new TextToSpeech(this, status -> {
            if (status != TextToSpeech.SUCCESS) { out.setText("TTS engine failed to initialize: " + status); return; }
            // populate the spinner with our engine's voices
            Set<Voice> vs = holder[0].getVoices();
            java.util.List<String> names = new java.util.ArrayList<>();
            for (org.json.JSONObject m : MainActivity.loadModels(this))
                names.add(m.optString("label", m.optString("model")));
            final java.util.List<Voice> engineVoices = new java.util.ArrayList<>();
            for (Voice v : vs) if (names.contains(v.getName())) engineVoices.add(v);
            java.util.List<String> labels = new java.util.ArrayList<>();
            for (Voice v : engineVoices) labels.add(v.getName() + " (" + v.getLocale() + ")");
            ArrayAdapter<String> ad = new ArrayAdapter<>(this,
                    android.R.layout.simple_spinner_item, labels);
            ad.setDropDownViewResource(android.R.layout.simple_spinner_dropdown_item);
            voices.setAdapter(ad);
            if (labels.isEmpty()) out.setText("No voices: configure the models first.");
            else out.setText("Ready: " + engineVoices.size() + " voices available.");
        }, "it.ttsserverproxy");

        speak.setOnClickListener(v -> {
            int pos = voices.getSelectedItemPosition();
            Set<Voice> vs = holder[0].getVoices();
            java.util.List<String> names = new java.util.ArrayList<>();
            for (org.json.JSONObject m : MainActivity.loadModels(this))
                names.add(m.optString("label", m.optString("model")));
            for (Voice vv : vs) {
                if (names.contains(vv.getName())) {
                    if (pos < 0 || vv.getName().equals(((String) voices.getSelectedItem()).split(" \\(")[0])) {
                        holder[0].setVoice(vv);
                        break;
                    }
                }
            }
            holder[0].setLanguage(Locale.ITALIAN);
            holder[0].speak(t.getText(), TextToSpeech.QUEUE_FLUSH, null, "proxy-test");
            out.setText("Request sent to the tts-server-proxy engine.");
        });

        all.setOnClickListener(v -> {
            java.util.List<String> names = new java.util.ArrayList<>();
            for (org.json.JSONObject m : MainActivity.loadModels(this))
                names.add(m.optString("label", m.optString("model")));
            Set<Voice> vs = holder[0].getVoices();
            java.util.List<Voice> engine = new java.util.ArrayList<>();
            for (Voice vv : vs) if (names.contains(vv.getName())) engine.add(vv);
            StringBuilder b2 = new StringBuilder();
            for (Voice vv : engine) {
                holder[0].setVoice(vv);
                holder[0].speak("Voice: " + vv.getName() + ". " + t.getText(), TextToSpeech.QUEUE_ADD, null, "t-" + vv.getName());
                b2.append(vv.getName()).append("\n");
            }
            out.setText("Queued:\n" + b2);
        });
    }
}
